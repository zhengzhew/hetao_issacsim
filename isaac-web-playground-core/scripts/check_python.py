import ast
from pathlib import Path
root=Path(__file__).parents[1]
count=0
for directory in ('bridge','tools','scripts','deploy/cloud'):
 for file in (root/directory).rglob('*.py'):
  ast.parse(file.read_text(encoding='utf-8-sig'),filename=str(file));count+=1
print(f'Python syntax: {count} files passed (no generated bytecode)')
